(* Enumerability of predicates generated by rules.

   The main result, [rules_enumerator]: a predicate that is the least set
   closed under a family of rules is enumerable, as long as the rule
   labels are enumerable and each rule computes its conclusion (if any)
   from the list of its premises. Any finitary inductive predicate fits
   this shape once each constructor's non-recursive arguments are moved
   into its label and its side conditions are made decidable (see
   README.md).

   This file depends only on the Rocq Stdlib. The definitions of
   [enumerator] and [enumerable] are the ones from the Coq Library of
   Undecidability Proofs, written out again here. RuleEnumUndec.v shows
   that the two versions agree, and RuleEnumStdpp.v obtains [enumeratorT]
   from stdpp's [Countable]. *)

From Stdlib Require Import List Arith Cantor Eqdep_dec.
Import ListNotations.

(** * Enumerability *)

(** [f] enumerates exactly the elements satisfying [P]. *)
Definition enumerator {X} (f : nat -> option X) (P : X -> Prop) : Prop :=
  forall x, P x <-> exists n, f n = Some x.

Definition enumerable {X} (P : X -> Prop) : Prop :=
  exists f : nat -> option X, enumerator f P.

(** [f] enumerates every element of [X]. *)
Definition enumeratorT {X} (f : nat -> option X) : Prop :=
  forall x : X, exists n, f n = Some x.

Definition enumerableT (X : Type) : Prop :=
  exists f : nat -> option X, enumeratorT f.

(** ** Enumerable types *)

Lemma nat_enumeratorT : enumeratorT (fun n => Some n).
Proof. intros n; now exists n. Qed.

Definition prod_enum {X Y} (f : nat -> option X) (g : nat -> option Y)
    (n : nat) : option (X * Y) :=
  let (a, b) := Cantor.of_nat n in
  match f a, g b with
  | Some x, Some y => Some (x, y)
  | _, _ => None
  end.

Lemma prod_enumeratorT {X Y} {f : nat -> option X} {g : nat -> option Y} :
  enumeratorT f -> enumeratorT g -> enumeratorT (prod_enum f g).
Proof.
  intros Hf Hg [x y].
  destruct (Hf x) as [a Ha], (Hg y) as [b Hb].
  exists (Cantor.to_nat (a, b)); unfold prod_enum.
  now rewrite Cantor.cancel_of_to, Ha, Hb.
Qed.

Definition sum_enum {X Y} (f : nat -> option X) (g : nat -> option Y)
    (n : nat) : option (X + Y) :=
  match Cantor.of_nat n with
  | (0, a) => option_map inl (f a)
  | (_, b) => option_map inr (g b)
  end.

Lemma sum_enumeratorT {X Y} {f : nat -> option X} {g : nat -> option Y} :
  enumeratorT f -> enumeratorT g -> enumeratorT (sum_enum f g).
Proof.
  intros Hf Hg [x|y].
  - destruct (Hf x) as [a Ha]; exists (Cantor.to_nat (0, a)); unfold sum_enum.
    now rewrite Cantor.cancel_of_to, Ha.
  - destruct (Hg y) as [b Hb]; exists (Cantor.to_nat (1, b)); unfold sum_enum.
    now rewrite Cantor.cancel_of_to, Hb.
Qed.

(** [list_enum_len f k] enumerates the lists of length [k]. *)
Fixpoint list_enum_len {X} (f : nat -> option X) (k n : nat) : option (list X) :=
  match k with
  | 0 => Some []
  | S k =>
      let (a, b) := Cantor.of_nat n in
      match f a, list_enum_len f k b with
      | Some x, Some xs => Some (x :: xs)
      | _, _ => None
      end
  end.

Definition list_enum {X} (f : nat -> option X) (n : nat) : option (list X) :=
  let (k, m) := Cantor.of_nat n in list_enum_len f k m.

Lemma list_enumeratorT {X} {f : nat -> option X} :
  enumeratorT f -> enumeratorT (list_enum f).
Proof.
  intros Hf l.
  assert (exists m, list_enum_len f (length l) m = Some l) as [m Hm].
  { induction l as [|x l [m Hm]]; [now exists 0|].
    destruct (Hf x) as [a Ha]; exists (Cantor.to_nat (a, m)); cbn [length list_enum_len].
    now rewrite Cantor.cancel_of_to, Ha, Hm. }
  exists (Cantor.to_nat (length l, m)); unfold list_enum.
  now rewrite Cantor.cancel_of_to.
Qed.

(** Enumerability transfers along surjections, e.g. from a sum/product
    encoding of a type of rule labels to the labels themselves. *)
Lemma map_enumeratorT {X Y} (f : nat -> option X) (g : X -> Y) :
  enumeratorT f -> (forall y, exists x, g x = y) ->
  enumeratorT (fun n => option_map g (f n)).
Proof.
  intros Hf Hg y.
  destruct (Hg y) as [x <-], (Hf x) as [n Hn].
  exists n; now rewrite Hn.
Qed.

(** ** Projections

    A predicate on a sum or sigma type restricts to each summand. This is
    how a family of mutual inductive predicates, presented as one
    predicate on tagged judgments, gives back each member. *)

Lemma enumerable_inl {A B} (P : A + B -> Prop) :
  enumerable P -> enumerable (fun a => P (inl a)).
Proof.
  intros [f Hf].
  exists (fun n => match f n with Some (inl a) => Some a | _ => None end).
  intros a; split.
  - intros [n Hn]%Hf; exists n; now rewrite Hn.
  - intros [n Hn]; apply Hf; exists n.
    destruct (f n) as [[a'|]|]; try discriminate.
    now injection Hn as ->.
Qed.

Lemma enumerable_inr {A B} (P : A + B -> Prop) :
  enumerable P -> enumerable (fun b => P (inr b)).
Proof.
  intros [f Hf].
  exists (fun n => match f n with Some (inr b) => Some b | _ => None end).
  intros b; split.
  - intros [n Hn]%Hf; exists n; now rewrite Hn.
  - intros [n Hn]; apply Hf; exists n.
    destruct (f n) as [[|b']|]; try discriminate.
    now injection Hn as ->.
Qed.

(** For an indexed family, recognising which index an enumerated element
    has needs decidable equality on the indices. *)
Lemma enumerable_sigT {I} {A : I -> Type}
    (eqI : forall i j : I, {i = j} + {i <> j}) (P : {i : I & A i} -> Prop) (i : I) :
  enumerable P -> enumerable (fun a : A i => P (existT A i a)).
Proof.
  intros [f Hf].
  exists (fun n => match f n with
           | Some (existT _ j a) =>
               match eqI j i with
               | left e => Some (eq_rect j A a i e)
               | right _ => None
               end
           | None => None
           end).
  intros a; split.
  - intros [n Hn]%Hf; exists n; rewrite Hn.
    destruct (eqI i i) as [e|]; [|contradiction].
    now rewrite (UIP_dec eqI e eq_refl).
  - intros [n Hn]; apply Hf; exists n.
    destruct (f n) as [[j b]|]; [|discriminate].
    destruct (eqI j i) as [<-|]; [|discriminate].
    now injection Hn as ->.
Qed.

(** * Checkers

    A predicate is enumerable if some checker over an enumerable type of
    certificates computes exactly its instances: enumerate the
    certificates and keep what they certify. *)

Definition checker_enum {D X} (eD : nat -> option D) (check : D -> option X)
    (n : nat) : option X :=
  match eD n with
  | Some d => check d
  | None => None
  end.

Lemma checker_enumerator {D X} (eD : nat -> option D) (check : D -> option X)
    (R : X -> Prop) :
  enumeratorT eD ->
  (forall d x, check d = Some x -> R x) ->
  (forall x, R x -> exists d, check d = Some x) ->
  enumerator (checker_enum eD check) R.
Proof.
  intros HeD Hs Hc x; split.
  - intros [d Hd]%Hc.
    destruct (HeD d) as [n Hn].
    exists n; unfold checker_enum; now rewrite Hn.
  - intros [n Hn]; unfold checker_enum in Hn.
    destruct (eD n) as [d|]; [|discriminate].
    exact (Hs d x Hn).
Qed.

Corollary checker_enumerable {D X} (check : D -> option X) (R : X -> Prop) :
  enumerableT D ->
  (forall d x, check d = Some x -> R x) ->
  (forall x, R x -> exists d, check d = Some x) ->
  enumerable R.
Proof.
  intros [eD HeD] Hs Hc.
  exists (checker_enum eD check); now apply checker_enumerator.
Qed.

(** Enumerability transfers back along a many-one reduction from an
    enumerable type into a type with decidable equality. *)
Lemma enumerable_reduce {X Y} (P : X -> Prop) (Q : Y -> Prop) (f : X -> Y) :
  enumerableT X ->
  (forall y1 y2 : Y, {y1 = y2} + {y1 <> y2}) ->
  (forall x, P x <-> Q (f x)) ->
  enumerable Q -> enumerable P.
Proof.
  intros [eX HeX] eqY Hf [eQ HeQ].
  apply (checker_enumerable
    (D := X * nat)
    (fun '(x, n) =>
       match eQ n with
       | Some y => if eqY (f x) y then Some x else None
       | None => None
       end)).
  - exists (prod_enum eX (fun n => Some n)).
    exact (prod_enumeratorT HeX nat_enumeratorT).
  - intros [x n] x' Hx'.
    destruct (eQ n) as [y|] eqn:E; [|discriminate].
    destruct (eqY (f x) y) as [<-|]; [|discriminate].
    injection Hx' as <-.
    apply Hf, HeQ; now exists n.
  - intros x [n Hn]%Hf%HeQ.
    exists (x, n); cbn; rewrite Hn.
    now destruct (eqY (f x) (f x)).
Qed.

(** * Rule systems

    A derivation is a postfix program over rule labels: [(l, n)] pops [n]
    conclusions off the stack and pushes the conclusion of [l] applied to
    them. Programs are lists of pairs, so they are enumerable as soon as
    the labels are. *)

Section RuleEnumerable.

Context {X L : Type} (rule : L -> list X -> option X).

Fixpoint rule_run (p : list (L * nat)) (st : list X) : option (list X) :=
  match p with
  | [] => Some st
  | (l, n) :: p =>
      match rule_run p st with
      | Some st' =>
          match rule l (firstn n st') with
          | Some x => Some (x :: skipn n st')
          | None => None
          end
      | None => None
      end
  end.

Lemma rule_run_app p q st :
  rule_run (p ++ q) st =
  match rule_run q st with Some st' => rule_run p st' | None => None end.
Proof.
  induction p as [|[l n] p IH]; cbn.
  - now destruct (rule_run q st).
  - rewrite IH; now destruct (rule_run q st).
Qed.

Lemma Forall_firstn' {A} (P : A -> Prop) n l :
  Forall P l -> Forall P (firstn n l).
Proof.
  revert l; induction n as [|n IH]; intros [|a l] H; cbn; auto.
  inversion H; subst; auto.
Qed.

Lemma Forall_skipn' {A} (P : A -> Prop) n l :
  Forall P l -> Forall P (skipn n l).
Proof.
  revert l; induction n as [|n IH]; intros [|a l] H; cbn; auto.
  inversion H; subst; auto.
Qed.

Lemma rule_run_sound (R : X -> Prop) :
  (forall l xs x, rule l xs = Some x -> Forall R xs -> R x) ->
  forall p st st', rule_run p st = Some st' -> Forall R st -> Forall R st'.
Proof.
  intros Hs p; induction p as [|[l n] p IH]; intros st st' Hrun HR; cbn in Hrun.
  - now injection Hrun as <-.
  - destruct (rule_run p st) as [st0|] eqn:E; [|discriminate].
    destruct (rule l (firstn n st0)) as [x|] eqn:Ex; [|discriminate].
    injection Hrun as <-.
    specialize (IH _ _ E HR).
    constructor.
    + exact (Hs l _ x Ex (Forall_firstn' _ n _ IH)).
    + exact (Forall_skipn' _ n _ IH).
Qed.

(** Every element of a rule-closed-minimal [R] has a program that pushes
    it onto any stack. *)
Lemma rule_run_complete (R : X -> Prop) :
  (forall S : X -> Prop,
     (forall l xs x, rule l xs = Some x -> Forall S xs -> S x) ->
     forall x, R x -> S x) ->
  forall x, R x -> exists p, forall st, rule_run p st = Some (x :: st).
Proof.
  intros Hc.
  apply (Hc (fun x => exists p, forall st, rule_run p st = Some (x :: st))).
  intros l xs x Hx HS.
  assert (exists q, forall st, rule_run q st = Some (xs ++ st)) as [q Hq].
  { clear Hx; induction HS as [|y ys [p Hp] _ [q Hq]]; [now exists []|].
    exists (p ++ q); intros st.
    now rewrite rule_run_app, Hq, Hp. }
  exists ((l, length xs) :: q); intros st; cbn.
  rewrite Hq, firstn_app, firstn_all, Nat.sub_diag, app_nil_r, Hx.
  now rewrite skipn_app, skipn_all, Nat.sub_diag.
Qed.

(** A program certifies [x] when, run on the empty stack, it leaves
    exactly [x]. *)
Definition rule_check (p : list (L * nat)) : option X :=
  match rule_run p [] with
  | Some [x] => Some x
  | _ => None
  end.

Definition rules_enum (eL : nat -> option L) : nat -> option X :=
  checker_enum (list_enum (prod_enum eL (fun n => Some n))) rule_check.

Theorem rules_enumerator (eL : nat -> option L) (R : X -> Prop) :
  enumeratorT eL ->
  (forall l xs x, rule l xs = Some x -> Forall R xs -> R x) ->
  (forall S : X -> Prop,
     (forall l xs x, rule l xs = Some x -> Forall S xs -> S x) ->
     forall x, R x -> S x) ->
  enumerator (rules_enum eL) R.
Proof.
  intros HeL Hs Hc.
  apply checker_enumerator.
  - exact (list_enumeratorT (prod_enumeratorT HeL nat_enumeratorT)).
  - intros p x; unfold rule_check.
    destruct (rule_run p []) as [[|y [|]]|] eqn:E; try discriminate.
    injection 1 as <-.
    assert (HR : Forall R [y]) by exact (rule_run_sound R Hs p [] [y] E (Forall_nil R)).
    now inversion HR.
  - intros x [p Hp]%(rule_run_complete R Hc).
    exists p; unfold rule_check; now rewrite Hp.
Qed.

Corollary rules_enumerable (R : X -> Prop) :
  enumerableT L ->
  (forall l xs x, rule l xs = Some x -> Forall R xs -> R x) ->
  (forall S : X -> Prop,
     (forall l xs x, rule l xs = Some x -> Forall S xs -> S x) ->
     forall x, R x -> S x) ->
  enumerable R.
Proof.
  intros [eL HeL] Hs Hc.
  exists (rules_enum eL); now apply rules_enumerator.
Qed.

End RuleEnumerable.
