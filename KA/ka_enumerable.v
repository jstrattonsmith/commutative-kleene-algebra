(* Enumerability of derivability in KA: the analogue of
   KA/preka_enumerable.v for the free Kleene algebra of KA/ka.v. If the
   pre-KA equivalence on terms over a countable pre-KA `P` is enumerable,
   so is `free_ka_eq`: it is generated by the rules `fk_rule`, and
   KA/preka_enumerable.v's `rules_enumerable` applies exactly as it does
   for the pre-KA axioms, with two extra rules for star induction. `fka_le_slice_enumerable_r`
   packages the result for the KA ordering `FKA e1 ⊑ FKA e2` on terms over
   a discrete countable monoid, with a fixed left-hand side. *)

Require Import ssreflect.
From Undecidability.Synthetic Require Import Definitions EnumerabilityFacts.
From Undecidability.Synthetic Require Import DecidabilityFacts.
From Undecidability.Synthetic Require Import MoreReducibilityFacts.
From stdpp Require Import base countable decidable.
From kacc Require Import KA.utils KA.algebra KA.pre_ka KA.preka_enumerable.
From kacc Require Import KA.ka.

Set Implicit Arguments.
Unset Strict Implicit.
Unset Printing Implicit Defensive.

Section FreeKAEqEnumerable.

Context (P : pre_ka) `{Countable (pre_ka_car P)}.

Implicit Types (e a b : ka_term P) (x y : P).

(* Rule labels for `free_ka_eq`. `K_pre k` uses the `k`-th pair of the
   pre-KA `≡`-enumerator. *)
Inductive fk_rl :=
  | K_refl (a : ka_term P)
  | K_sym | K_trans | K_join | K_mul | K_star | K_ubot | K_indl | K_indr
  | K_pre (k : nat)
  | K_ujoin (x y : P)
  | K_ustar (x : P).

Global Instance fk_rl_eq_dec : EqDecision fk_rl.
Proof. solve_decision. Defined.

Global Instance fk_rl_countable : Countable fk_rl.
Proof.
refine (inj_countable'
  (λ l, match l with
        | K_refl a => inl a
        | K_sym => inr (inl 0) | K_trans => inr (inl 1) | K_join => inr (inl 2)
        | K_mul => inr (inl 3) | K_star => inr (inl 4) | K_ubot => inr (inl 5)
        | K_indl => inr (inl 6) | K_indr => inr (inl 7)
        | K_pre k => inr (inr (inl k))
        | K_ujoin x y => inr (inr (inr (inl (x, y))))
        | K_ustar x => inr (inr (inr (inr x)))
        end)
  (λ u, match u with
        | inl a => K_refl a
        | inr (inl 0) => K_sym | inr (inl 1) => K_trans | inr (inl 2) => K_join
        | inr (inl 3) => K_mul | inr (inl 4) => K_star | inr (inl 5) => K_ubot
        | inr (inl 6) => K_indl | inr (inl _) => K_indr
        | inr (inr (inl k)) => K_pre k
        | inr (inr (inr (inl (x, y)))) => K_ujoin x y
        | inr (inr (inr (inr x))) => K_ustar x
        end) _)%nat.
by case.
Defined.

Section WithEnum.

Variable g : nat → option (ka_term P * ka_term P).

Definition ind_l_concl (p : ka_term P * ka_term P) :
    option (ka_term P * ka_term P) :=
  match p with
  | (ka_term_join (ka_term_join e2 (ka_term_mul e1 e3)) e3', e3'') =>
      if decide (e3 = e3' ∧ e3' = e3'') is left _ then
        Some (star e1 ⋅ e2 ⊔ e3, e3)
      else None
  | _ => None
  end.

Definition ind_r_concl (p : ka_term P * ka_term P) :
    option (ka_term P * ka_term P) :=
  match p with
  | (ka_term_join (ka_term_join e2 (ka_term_mul e3 e1)) e3', e3'') =>
      if decide (e3 = e3' ∧ e3' = e3'') is left _ then
        Some (e2 ⋅ star e1 ⊔ e3, e3)
      else None
  | _ => None
  end.

Lemma ind_l_concl_inv p a b :
  ind_l_concl p = Some (a, b) →
  ∃ e1 e2 e3, p = ((e2 ⊔ e1 ⋅ e3) ⊔ e3, e3) ∧
    a = star e1 ⋅ e2 ⊔ e3 ∧ b = e3.
Proof.
rewrite /ind_l_concl => Hc; repeat case_match; simplify_eq.
by destruct_and!; subst; eauto 10.
Qed.

Lemma ind_r_concl_inv p a b :
  ind_r_concl p = Some (a, b) →
  ∃ e1 e2 e3, p = ((e2 ⊔ e3 ⋅ e1) ⊔ e3, e3) ∧
    a = e2 ⋅ star e1 ⊔ e3 ∧ b = e3.
Proof.
rewrite /ind_r_concl => Hc; repeat case_match; simplify_eq.
by destruct_and!; subst; eauto 10.
Qed.

Definition fk_rule (l : fk_rl) (ps : list (ka_term P * ka_term P)) :
    option (ka_term P * ka_term P) :=
  match l, ps with
  | K_refl a, [] => Some (a, a)
  | K_sym, [(a, b)] => Some (b, a)
  | K_trans, [(a, b); (b', c)] =>
      if decide (b = b') is left _ then Some (a, c) else None
  | K_pre k, [] => g k
  | K_join, [(a, b); (c, e)] => Some (a ⊔ c, b ⊔ e)
  | K_mul, [(a, b); (c, e)] => Some (a ⋅ c, b ⋅ e)
  | K_star, [(a, b)] => Some (star a, star b)
  | K_ubot, [] => Some (Unit ⊥, ⊥)
  | K_ujoin x y, [] => Some (Unit (x ⊔ y), Unit x ⊔ Unit y)
  | K_ustar x, [] => Some (Unit (star x), star (Unit x))
  | K_indl, [p] => ind_l_concl p
  | K_indr, [p] => ind_r_concl p
  | _, _ => None
  end.

End WithEnum.

Theorem free_ka_eq_enumerable :
  enumerable (fun p : ka_term P * ka_term P => p.1 ≡ p.2) →
  enumerable (fun p : ka_term P * ka_term P => free_ka_eq p.1 p.2).
Proof.
move=> [g Hg].
apply: (rules_enumerable (rule := fk_rule g)).
- move=> l ps [a b] E HR /=; rewrite /fk_rule in E.
  destruct l; repeat case_match; simplify_eq/=; decompose_Forall_hyps.
  all: try by [ exact: fk_refl | exact: fk_sym | exact: fk_trans
              | exact: fk_join_proper | exact: fk_mul_proper
              | exact: fk_star_proper | exact: fk_unit_bottom
              | exact: fk_unit_join | exact: fk_unit_star ].
  + move: E => /ind_l_concl_inv [e1 [e2 [e3 [Ep [-> ->]]]]].
    by subst; apply: fk_star_ind_l.
  + move: E => /ind_r_concl_inv [e1 [e2 [e3 [Ep [-> ->]]]]].
    by subst; apply: fk_star_ind_r.
  + match goal with H : g ?k = _ |- _ =>
      by apply: fk_pre; apply/(Hg (a, b)); exists k end.
- move=> S HS [a b] /=; elim.
  + by move=> x; apply: (HS (K_refl x) []).
  + by move=> x y _ ?; apply: (HS K_sym [(x, y)]); repeat constructor.
  + move=> x y z _ ? _ ?; apply: (HS K_trans [(x, y); (y, z)]).
      by rewrite /= decide_True.
    by repeat constructor.
  + move=> x y /(Hg (x, y)) [n Hn].
    by apply: (HS (K_pre n) []) => //=; rewrite Hn.
  + by move=> x x' y y' _ ? _ ?; apply: (HS K_join [(x, x'); (y, y')]);
      repeat constructor.
  + by move=> x x' y y' _ ? _ ?; apply: (HS K_mul [(x, x'); (y, y')]);
      repeat constructor.
  + by move=> x y _ ?; apply: (HS K_star [(x, y)]); repeat constructor.
  + by apply: (HS K_ubot []).
  + by move=> x y; apply: (HS (K_ujoin x y) []).
  + by move=> x; apply: (HS (K_ustar x) []).
  + move=> x y z _ ?; apply: (HS K_indl [((y ⊔ x ⋅ z) ⊔ z, z)]).
      by rewrite /= decide_True.
    by repeat constructor.
  + move=> x y z _ ?; apply: (HS K_indr [((y ⊔ z ⋅ x) ⊔ z, z)]).
      by rewrite /= decide_True.
    by repeat constructor.
Qed.

End FreeKAEqEnumerable.

(** * The KA ordering on terms over a discrete countable monoid *)

Section KaLeqEnumerable.

Context (T : monoid).
Context `{HeqT : !RelDecision (@Logic.eq (monoid_car T))}.
Context `{!Countable (monoid_car T)} (HLeibniz : LeibnizEquiv (monoid_car T)).

Lemma fka_eq_enumerable :
  enumerable (fun p : ka_term (ka_term T) * ka_term (ka_term T) =>
                free_ka_eq p.1 p.2).
Proof.
apply: (@free_ka_eq_enumerable (ka_term_pre_ka T)).
apply: (@ka_eq_enumerable (ka_term_monoid T)).
apply: ka_eq_enumerable.
exact: T_equiv_enumerable HLeibniz.
Qed.

Lemma fka_le_iff (e1 e2 : ka_term T) :
  FKA e1 ⊑ FKA e2 ↔ free_ka_eq (Unit (e1 ⊔ e2)) (Unit e2).
Proof. exact: default_sqsubseteq_eq. Qed.

Theorem fka_le_slice_enumerable_r
    (lhs : ka_term T) (rhs : nat → ka_term T) :
  enumerable (fun z => FKA lhs ⊑ FKA (rhs z)).
Proof.
apply: (enumerable_reduce (f := fun z => (Unit (lhs ⊔ rhs z), Unit (rhs z)))
          (Q := fun p : ka_term (ka_term T) * _ => free_ka_eq p.1 p.2)).
- move=> z; exact: fka_le_iff.
- exact: fka_eq_enumerable.
Qed.

End KaLeqEnumerable.
