(** The additive monoid of natural numbers is generated by `1`. *)

Global Program Instance nat_add_gen : MonoidGen unit nat_add_monoid := {|
  generator_interp _ := 1%nat : nat_add_monoid;
  generate n := repeat tt n;
|}.
Next Obligation. by elim=> //= n {1}->. Qed.

Section BalancedKA.

Context {A : setoid} `{!LeibnizEquiv A, !EqDecision A, !Finite A}.

Notation M := (prod_monoid (list_monoid A) nat_add_monoid).

Implicit Types (w : list A) (x : ka_term M).

Definition letA : ka_term M := ⨆ t ∈ enum A, Unit ([t], 0%nat).
Definition letB : ka_term M := Unit ([], 1%nat).

(* `Σ*`: the star of all generators of `list A * nat`. *)
Definition sigma_top : ka_term M := @pseudo_top (A + unit) M _ _ _.

(* The words with too many or too few commuting letters. *)
Definition unbal : ka_term M :=
  (letA ⋅ star letA ⊔ letB ⋅ star letB) ⋅ bal_star.

Lemma sigma_top_eq : sigma_top ≡ star (letA ⊔ letB).
Proof.
rewrite /sigma_top /pseudo_top /=; f_equiv.
rewrite join_list_app !join_list_map /= ka_join_right_id.
by [].
Qed.

Lemma letA_letB : letA ⋅ letB ≡ bal_gen.
Proof.
rewrite /letA /bal_gen join_list_left_dist.
by apply: join_list_proper => // t; rewrite -ka_mul_distr.
Qed.

Lemma letB_letA : letB ⋅ letA ≡ bal_gen.
Proof.
rewrite /letA /bal_gen join_list_right_dist.
by apply: join_list_proper => // t; rewrite -ka_mul_distr.
Qed.

Theorem sigma_top_ka : FKA sigma_top ≡ FKA (bal_star ⊔ unbal).
Proof.
have Hc : FKA letA ⋅ FKA letB ≡ FKA letB ⋅ FKA letA.
  by apply: fka_of_pre; rewrite letA_letB letB_letA.
rewrite (fka_of_pre sigma_top_eq).
change (star (FKA letA ⊔ FKA letB) ≡ FKA (bal_star ⊔ unbal)).
rewrite (ka_star_join_comm Hc).
change (FKA ((1 ⊔ letA ⋅ star letA ⊔ letB ⋅ star letB) ⋅ star (letA ⋅ letB))
        ≡ FKA (bal_star ⊔ unbal)).
apply: fka_of_pre; rewrite letA_letB /unbal /bal_star.
by rewrite !pre_ka_left_dist left_id assoc.
Qed.

Theorem ka_top_complete x : bal_star ⊑ x → FKA sigma_top ⊑ FKA (x ⊔ unbal).
Proof.
move=> H; rewrite sigma_top_ka; apply: fka_le_of_pre.
by rewrite H.
Qed.

Lemma l_letA y : l letA y → ∃ t, y = ([t], 0%nat).
Proof.
rewrite /letA semi_lattice_morphism_join_list elem_of_lang_join_list.
by case=> t [] _ /M_equiv_eq ->; exists t.
Qed.

Lemma l_letB y : l letB y → y = ([], 1%nat).
Proof. exact: M_equiv_eq. Qed.

Lemma l_unbal w k : l unbal (w, k) → k ≠ length w.
Proof.
case/l_pair_mul_inv => w1 [k1 [w2 [k2 [-> [-> [H1 /l_bal_star /= ->]]]]]].
rewrite length_app.
have [] : l (letA ⋅ star letA) (w1, k1) ∨ l (letB ⋅ star letB) (w1, k1).
  exact: H1.
- case/l_pair_mul_inv => u1 [a1 [u2 [a2 [-> [-> [/l_letA [t [-> ->]] H2]]]]]].
  have -> : a2 = 0%nat.
    move: H2; apply: (l_star_elim (Pr := λ _ k, k = 0%nat)) => //.
    by move=> ???? /l_letA [? [_ ->]] ->.
  rewrite length_app /=; lia.
- case/l_pair_mul_inv => u1 [a1 [u2 [a2 [-> [-> [/l_letB [-> ->]] H2]]]]].
  have -> : u2 = [].
    move: H2; apply: (l_star_elim (Pr := λ w _, w = [])) => //.
    by move=> ???? /l_letB [-> _] ->.
  rewrite /=; lia.
Qed.

Theorem ka_top_sound x :
  FKA sigma_top ⊑ FKA (x ⊔ unbal) → ∀ w, l x (w, length w).
Proof.
move=> H w.
have Hb : FKA bal_star ⊑ FKA (x ⊔ unbal).
  apply: transitivity H; rewrite sigma_top_ka; apply: fka_le_of_pre.
  exact: sqsubseteq_join_left.
have Hw : l bal_star (w, length w) by apply/l_bal_star.
have [] : l x (w, length w) ∨ l unbal (w, length w) := fka_lang Hb Hw.
  by [].
by move/l_unbal.
Qed.

End BalancedKA.
