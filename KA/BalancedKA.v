(* From balanced universality to full universality in KA, over the monoid
   `list A * nat` of KA/balanced.v. Its generators are the letters
   `([t], 0)` and the commuting letter `([], 1)`, so `Σ*` (`sigma_top`, an
   instance of `pseudo_top`) is `star (letA ⊔ letB)`. Since `letA` and
   `letB` commute, KA/ka.v's `ka_star_join_comm` splits `Σ*` into the
   balanced words `bal_star` and the words with too many or too few
   commuting letters (`unbal`):

     KA ⊢ Σ* ≡ bal_star ⊔ unbal                       (sigma_top_ka)

   Hence, for any `x`, a pre-KA proof of `bal_star ⊑ x` gives a KA proof
   of `Σ* ⊑ x ⊔ unbal`, i.e. `FKA sigma_top ⊑ FKA (x ⊔ unbal)`
   (`ka_top_complete`), and conversely a KA proof of `Σ* ⊑ x ⊔ unbal` puts
   every balanced word in the language of `x` (`ka_top_sound`), since
   `unbal` contains no balanced word. The splitting needs star induction:
   in pre-KA it can fail. *)

