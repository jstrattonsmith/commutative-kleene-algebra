(** * Enumerability of [ka_eq]

    We show that if the equivalence relation [≡] of the carrier monoid
    [T] is enumerable, then so is the induced equivalence [ka_eq] on
    [ka_term T].  "Enumerable" is the notion from the
    coq-library-undecidability development
    ([Undecidability.Synthetic.Definitions.enumerable]).

    The carrier is assumed [Countable] (this yields decidable Leibniz
    equality on [ka_term T], which is needed to close the relation under
    transitivity, and an enumeration of [ka_term T]).

    The proof presents [ka_eq] as generated by a countable family of
    computable rules ([ka_rule]) and applies [rules_enumerable]. *)

(** Tags for the twelve "constant" equational axiom schemes. *)
Inductive ax_tag :=
  | AMul | LMulId | RMulId | AJoin | CJoin | LJoinId
  | IJoin | LAbs | RAbs | DstR | DstL | SUnf.

Global Instance ax_tag_eq_dec : EqDecision ax_tag.
Proof. solve_decision. Defined.

Open Scope nat_scope.
Definition ax_to_nat (t : ax_tag) : nat :=
  match t with
  | AMul => 0 | LMulId => 1 | RMulId => 2 | AJoin => 3 | CJoin => 4
  | LJoinId => 5 | IJoin => 6 | LAbs => 7 | RAbs => 8 | DstR => 9
  | DstL => 10 | SUnf => 11
  end.
Definition nat_to_ax (n : nat) : ax_tag :=
  match n with
  | 0 => AMul | 1 => LMulId | 2 => RMulId | 3 => AJoin | 4 => CJoin
  | 5 => LJoinId | 6 => IJoin | 7 => LAbs | 8 => RAbs | 9 => DstR
  | 10 => DstL | _ => SUnf
  end.
Close Scope nat_scope.

Global Instance ax_tag_countable : Countable ax_tag.
Proof. refine (inj_countable' ax_to_nat nat_to_ax _); by case. Defined.

Section KaEqEnumerable.

Context (T : monoid) `{Countable T}.

Implicit Types (e a b c : ka_term T) (x y : T).

(** Rule labels for [ka_eq]. [L_unit k] uses the [k]-th pair of the
    carrier's [≡]-enumerator for a [ka_unit_proper] step, and
    [L_ax t a b c] is an instance of a constant axiom scheme. *)
Inductive ka_rl :=
  | L_refl (a : ka_term T)
  | L_sym | L_trans | L_mulc | L_joinc | L_starc
  | L_muldistr (x y : T)
  | L_unit (k : nat)
  | L_ax (t : ax_tag) (a b c : ka_term T).

Global Instance ka_rl_eq_dec : EqDecision ka_rl.
Proof. solve_decision. Defined.

Global Instance ka_rl_countable : Countable ka_rl.
Proof.
refine (inj_countable'
  (λ l, match l with
        | L_refl a => inl a
        | L_sym => inr (inl 0%nat) | L_trans => inr (inl 1%nat)
        | L_mulc => inr (inl 2%nat) | L_joinc => inr (inl 3%nat)
        | L_starc => inr (inl 4%nat)
        | L_muldistr x y => inr (inr (inl (x, y)))
        | L_unit k => inr (inr (inr (inl k)))
        | L_ax t a b c => inr (inr (inr (inr (t, a, b, c))))
        end)
  (λ u, match u with
        | inl a => L_refl a
        | inr (inl 0%nat) => L_sym | inr (inl 1%nat) => L_trans
        | inr (inl 2%nat) => L_mulc | inr (inl 3%nat) => L_joinc
        | inr (inl _) => L_starc
        | inr (inr (inl (x, y))) => L_muldistr x y
        | inr (inr (inr (inl k))) => L_unit k
        | inr (inr (inr (inr (t, a, b, c)))) => L_ax t a b c
        end) _).
by case.
Defined.

Section WithEnum.

Variable g : nat → option (T * T).

(** The conclusion of each rule from its premises, or [None] if the
    premises do not fit (a transitivity whose two halves do not meet, or
    an [L_unit] pointing past the enumerator). *)
Definition ka_rule (l : ka_rl) (ps : list (ka_term T * ka_term T)) :
    option (ka_term T * ka_term T) :=
  match l, ps with
  | L_refl a, [] => Some (a, a)
  | L_sym, [(a, b)] => Some (b, a)
  | L_trans, [(a, b); (b', c)] =>
      if decide (b = b') is left _ then Some (a, c) else None
  | L_mulc, [(a, b); (c, e)] => Some (a ⋅ c, b ⋅ e)
  | L_joinc, [(a, b); (c, e)] => Some (a ⊔ c, b ⊔ e)
  | L_starc, [(a, b)] => Some (star a, star b)
  | L_muldistr x y, [] => Some (Unit (x ⋅ y), Unit x ⋅ Unit y)
  | L_unit k, [] => if g k is Some (x, y) then Some (Unit x, Unit y) else None
  | L_ax AMul a b c, [] => Some (a ⋅ (b ⋅ c), (a ⋅ b) ⋅ c)
  | L_ax LMulId a _ _, [] => Some (1 ⋅ a, a)
  | L_ax RMulId a _ _, [] => Some (a ⋅ 1, a)
  | L_ax AJoin a b c, [] => Some (a ⊔ (b ⊔ c), (a ⊔ b) ⊔ c)
  | L_ax CJoin a b _, [] => Some (a ⊔ b, b ⊔ a)
  | L_ax LJoinId a _ _, [] => Some (⊥ ⊔ a, a)
  | L_ax IJoin a _ _, [] => Some (a ⊔ a, a)
  | L_ax LAbs a _ _, [] => Some (⊥ ⋅ a, ⊥)
  | L_ax RAbs a _ _, [] => Some (a ⋅ ⊥, ⊥)
  | L_ax DstR a b c, [] => Some (a ⋅ (b ⊔ c), a ⋅ b ⊔ a ⋅ c)
  | L_ax DstL a b c, [] => Some ((a ⊔ b) ⋅ c, a ⋅ c ⊔ b ⋅ c)
  | L_ax SUnf a _ _, [] => Some (star a, 1 ⊔ a ⋅ star a)
  | _, _ => None
  end.

End WithEnum.

Theorem ka_eq_enumerable :
  enumerable (fun p : T * T => p.1 ≡ p.2) →
  enumerable (fun p : ka_term T * ka_term T => p.1 ≡ p.2).
Proof.
move=> [g Hg].
apply: (rules_enumerable (rule := ka_rule g)).
- move=> l ps [a b] E HR /=; rewrite /ka_rule in E.
  destruct l; repeat case_match; simplify_eq/=; decompose_Forall_hyps.
  all: try by [ symmetry | etransitivity | apply: ka_mul_proper
              | apply: ka_join_proper | apply: ka_star_proper
              | apply: ka_mul_distr | apply: ka_mul_assoc
              | apply: ka_mul_left_id | apply: ka_mul_right_id
              | apply: ka_join_assoc | apply: ka_join_comm
              | apply: ka_join_left_id | apply: ka_join_idemp
              | apply: ka_mul_left_absorb | apply: ka_mul_right_absorb
              | apply: ka_mul_join_right | apply: ka_mul_join_left
              | apply: ka_star_unfold ].
  by apply: ka_unit_proper; apply/(Hg (_, _)); eexists.
- move=> S HS [a b] /=; elim.
  + by move=> x; apply: (HS (L_refl x) []).
  + by move=> x y _ ?; apply: (HS L_sym [(x, y)]); repeat constructor.
  + move=> x y z _ ? _ ?; apply: (HS L_trans [(x, y); (y, z)]).
      by rewrite /= decide_True.
    by repeat constructor.
  + by move=> x y; apply: (HS (L_muldistr x y) []).
  + move=> x y /(Hg (x, y)) [n Hn].
    by apply: (HS (L_unit n) []) => //=; rewrite Hn.
  + by move=> x y _ ? z w _ ?; apply: (HS L_mulc [(x, y); (z, w)]);
      repeat constructor.
  + by move=> x y _ ? z w _ ?; apply: (HS L_joinc [(x, y); (z, w)]);
      repeat constructor.
  + by move=> x y _ ?; apply: (HS L_starc [(x, y)]); repeat constructor.
  + by move=> x y z; apply: (HS (L_ax AMul x y z) []).
  + by move=> x; apply: (HS (L_ax LMulId x x x) []).
  + by move=> x; apply: (HS (L_ax RMulId x x x) []).
  + by move=> x y z; apply: (HS (L_ax AJoin x y z) []).
  + by move=> x y; apply: (HS (L_ax CJoin x y x) []).
  + by move=> x; apply: (HS (L_ax LJoinId x x x) []).
  + by move=> x; apply: (HS (L_ax IJoin x x x) []).
  + by move=> x; apply: (HS (L_ax LAbs x x x) []).
  + by move=> x; apply: (HS (L_ax RAbs x x x) []).
  + by move=> u v w; apply: (HS (L_ax DstR u v w) []).
  + by move=> u v w; apply: (HS (L_ax DstL u v w) []).
  + by move=> t; apply: (HS (L_ax SUnf t t t) []).
Qed.

(** The canonical order [⊑] on [ka_term T], characterised by
    [x ⊑ y ↔ x ⊔ y ≡ y], is enumerable whenever the carrier's [≡] is: it
    reduces to [ka_eq] along [(x, y) ↦ (x ⊔ y, y)], and enumerability is
    preserved under reductions with an enumerable source and discrete
    target. *)
Theorem ka_sqsubseteq_enumerable :
  enumerable (fun p : T * T => p.1 ≡ p.2) →
  enumerable (fun p : ka_term T * ka_term T => p.1 ⊑ p.2).
Proof.
move=> Henum.
eapply (enumerable_reduce (f := fun p => (p.1 ⊔ p.2, p.2))
          (Q := fun q => q.1 ≡ q.2)).
- move=> [a b] /=. exact: sqsubseteq_iff.
- exact: ka_eq_enumerable Henum.
Qed.

End KaEqEnumerable.

(** * Enumerability of a fixed-rhs "slice" of [⊑]

    Generic packaging of [ka_sqsubseteq_enumerable] for the common shape
    every KA-term-inequality undecidability argument in this project
    needs: a carrier monoid [T] with decidable, countable, Leibniz-equal
    [≡] gives [⊑] on [ka_term T] enumerable (via [KA_ineq_over]), and
    hence any fixed-rhs SLICE of it (a family [lhs : nat -> ka_term T]
    against one fixed [rhs]) enumerable too, via [enumerable_reduce].
    Originally proved twice, once each for the machine-specific carrier
    [TmMonoid] (CKAUndec/KEnumerable.v) and the binary-alphabet carrier
    [Tm_bin] (CKAUndec/BinaryAlphabetMComplete.v) -- factored out here
    since neither proof used anything but this file's own machinery. *)

Section SliceEnumerable.

Context (T : monoid).
Context `{HeqT : !RelDecision (@Logic.eq (monoid_car T))}.
Context `{!Countable (monoid_car T)} (HLeibniz : LeibnizEquiv (monoid_car T)).

Instance T_equiv_dec (x y : monoid_car T) : Decision (x ≡ y).
Proof.
destruct (HeqT x y) as [-> | Hne].
- left. reflexivity.
- right. intros Heq. apply Hne. exact (leibniz_equiv x y Heq).
Defined.

Lemma T_equiv_enumerable : enumerable (fun p : monoid_car T * monoid_car T => p.1 ≡ p.2).
Proof.
apply: dec_count_enum.
2: exact: (@countable_enumerableT (monoid_car T * monoid_car T) _ _).
exists (fun p => bool_decide (p.1 ≡ p.2)).
intros p. unfold reflects. symmetry. apply bool_decide_eq_true.
Qed.

Definition KA_ineq_over : ka_term (monoid_car T) * ka_term (monoid_car T) -> Prop :=
  fun p => p.1 ⊑ p.2.

Theorem KA_ineq_over_enumerable : enumerable KA_ineq_over.
Proof. exact: ka_sqsubseteq_enumerable T_equiv_enumerable. Qed.

Theorem slice_enumerable
    (lhs : nat -> ka_term (monoid_car T)) (rhs : ka_term (monoid_car T)) :
  enumerable (fun z => lhs z ⊑ rhs).
Proof.
apply: (enumerable_reduce (f := fun z => (lhs z, rhs)) (Q := KA_ineq_over))
  => //.
exact: KA_ineq_over_enumerable.
Qed.

(* The same with the left-hand side fixed and the right-hand side
   varying, as in CKAUndec/UnivMComplete.v's `bal_star ⊑ e`. *)
Theorem slice_enumerable_r
    (lhs : ka_term (monoid_car T)) (rhs : nat -> ka_term (monoid_car T)) :
  enumerable (fun z => lhs ⊑ rhs z).
Proof.
apply: (enumerable_reduce (f := fun z => (lhs, rhs z)) (Q := KA_ineq_over))
  => //.
exact: KA_ineq_over_enumerable.
Qed.

End SliceEnumerable.
