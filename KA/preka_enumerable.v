(* Shows that if a monoid `T`'s own equivalence `≡` is enumerable, so is
   the induced `ka_eq`/`⊑` on `ka_term T`. The generic argument is
   KA/rules_enumerable.v's `rules_enumerable`: a predicate generated by a
   countable family of computable rules is enumerable. `ka_eq` is
   generated by the rules `ka_rule` (the 12 pre-KA axiom schemes,
   congruence, and the carrier's own `≡`). This is the "finitary axiomatization gives enumerability"
   argument that CKAUndec/KEnumerable.v instantiates for the MM2
   encoding's own carrier monoid, giving the enumerability of the KA-term
   inequality relation needed for the final Sigma^0_1-completeness
   result. *)

